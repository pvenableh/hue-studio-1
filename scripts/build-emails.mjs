// Compiles the MJML sources and bundles the transactional templates into a
// TS module so server routes can import the HTML directly (no runtime fs /
// storage lookups — works the same in dev and in the production bundle).
//
// Run via `pnpm emails:build`.
import { execSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'

// 1. Compile every MJML source → emails/compiled/*.html
execSync('npx mjml emails/*.mjml -o emails/compiled/', { stdio: 'inherit' })

// 2. Inline the transactional templates that server routes send at runtime.
const templates = {
  requestNotificationHtml: 'emails/compiled/request-notification.html',
  requestConfirmationHtml: 'emails/compiled/request-confirmation.html',
}

const banner = '// AUTO-GENERATED by scripts/build-emails.mjs — do not edit by hand.\n'
  + '// Edit the MJML in emails/ and run `pnpm emails:build` to regenerate.\n\n'

const body = Object.entries(templates)
  .map(([name, path]) => `export const ${name} = ${JSON.stringify(readFileSync(path, 'utf8'))}\n`)
  .join('\n')

writeFileSync('server/utils/emailTemplates.ts', banner + body)
console.log('Wrote server/utils/emailTemplates.ts')
